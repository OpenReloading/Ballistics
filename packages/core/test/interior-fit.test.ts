import { describe, expect, it } from 'vitest'
import { nth } from '../src/errors.ts'
import {
  fitPowder,
  InputError,
  type InteriorLoad,
  interior,
  type LadderPoint,
  PowderFitError,
  predictPowder,
} from '../src/index.ts'
import { normals } from './random.ts'

/** Synthetic rifle load (apps/docs/docs/models/interior-powder-fit.md): truth B_a 0.45 1/s, p_st 30 MPa. */
const load = (vivacity = 0.45, startPressure = 30e6): InteriorLoad => ({
  chamber: { volume: 3.4e-6, boreArea: 3.75e-5, boreDiameter: 6.9e-3 },
  barrel: { length: 0.6, twist: 0.254 },
  bullet: { mass: 0.0095 },
  charge: 0.0028,
  propellant: {
    specificEnergy: 3.9e6,
    gamma: 1.23,
    density: 1600,
    covolume: 1e-3,
    burn: {
      kind: 'vivacity',
      vivacity,
      exponent: 1,
      referencePressure: 98066.5,
      form: { kind: 'twoStage', a: 0.8, m: 0.5, q: 0.5, z1: 0.8 },
    },
  },
  propellantTemperature: 294.15,
  ignitionPressure: 5e6,
  startPressure,
})
const charges = [2.6e-3, 2.7e-3, 2.8e-3, 2.9e-3, 3e-3]
/** Fixed noise pattern in units of sigma. */
const noise = [1, -1, 0.5, -1.5, 0.8]

/** Ladder generated by `interior`; `v` and `p` are the sigmas, 0 for none, `n` scales the noise. */
const ladder = (truth: InteriorLoad, v: number, p: number, n = 0): LadderPoint[] =>
  charges.map((charge, i) => {
    const r = interior({ ...truth, charge })
    if (!r.valid) throw new Error(r.reason)
    return {
      charge,
      muzzleVelocity: r.muzzleVelocity + n * nth(noise, i) * (v || 1),
      ...(v ? { velocitySigma: v } : {}),
      ...(p
        ? { peakPressure: r.peakBreechPressure + n * nth(noise, (i + 2) % 5) * p, pressureSigma: p }
        : {}),
    }
  })

const failure = (f: () => unknown) => {
  try {
    f()
  } catch (e) {
    if (e instanceof PowderFitError) return e
    throw e
  }
  throw new Error('no error')
}
const rel = (a: number, b: number) => Math.abs(a / b - 1)

describe('powder fit round trips', () => {
  it('fits the burn coefficient alone by default and keeps the start pressure', () => {
    const r = fitPowder(load(0.38), ladder(load(), 3, 0))
    expect(r.parameters.map((p) => p.name)).toEqual(['burnRate'])
    expect(nth(r.parameters, 0).initial).toBe(0.38)
    expect(rel(nth(r.parameters, 0).value, 0.45)).toBeLessThan(1e-6)
    expect(r.load.startPressure).toBe(30e6)
    expect(r.degreesOfFreedom).toBe(4)
    // one evaluation runs every charge once: the start (1), the Jacobian by central differences
    // (2) and per step but the last, which ends below the step limit without a run, the step (1)
    // and the Jacobian after it (2)
    expect(r.runCount).toBe(charges.length * 3 * r.iterations)
    // maxIterations counts steps: the fit's own count passes, one fewer does not
    const again = fitPowder(load(0.38), ladder(load(), 3, 0), { maxIterations: r.iterations })
    expect(again.parameters).toEqual(r.parameters)
    const short = failure(() =>
      fitPowder(load(0.38), ladder(load(), 3, 0), { maxIterations: r.iterations - 1 }),
    )
    expect(short.reason).toBe('not-converged')
  })

  it('keeps the default with pressures and a start pressure of 0', () => {
    const r = fitPowder(load(0.38, 0), ladder(load(0.45, 0), 3, 10e6))
    expect(r.parameters.map((p) => p.name)).toEqual(['burnRate'])
    expect(rel(nth(r.parameters, 0).value, 0.45)).toBeLessThan(1e-6)
    expect(r.load.startPressure).toBe(0)
    expect(r.degreesOfFreedom).toBe(9)
  })

  it('moves the coefficient of a geometric law', () => {
    const sphere = (coefficient: number): InteriorLoad => ({
      ...load(),
      propellant: {
        ...load().propellant,
        burn: {
          kind: 'geometric',
          coefficient,
          exponent: 0.9,
          grain: { shape: 'sphere', diameter: 4e-4 },
        },
      },
    })
    const r = fitPowder(sphere(4e-9), ladder(sphere(5e-9), 3, 0))
    expect(rel(nth(r.parameters, 0).value, 5e-9)).toBeLessThan(1e-6)
    expect(r.load.propellant.burn).toEqual({
      ...sphere(5e-9).propellant.burn,
      coefficient: nth(r.parameters, 0).value,
    })
  })
})

describe('powder fit uncertainty', () => {
  const both = ['burnRate', 'startPressure'] as const
  const noisy = fitPowder(load(0.38, 20e6), ladder(load(), 3, 5e6, 1), { parameters: both })

  it('recovers both parameters with pressures within the reported uncertainty', () => {
    const truth = [0.45, 30e6]
    noisy.parameters.forEach((p, k) => {
      expect(p.standardUncertainty).toBeGreaterThan(0)
      expect(Math.abs(p.value - nth(truth, k))).toBeLessThan(2 * (p.standardUncertainty ?? 0))
    })
    expect(noisy.degreesOfFreedom).toBe(8)
    // apps/docs/docs/models/interior-powder-fit.md, "Identifiability": sigma(p_st) 6.15 MPa
    expect(rel(nth(noisy.parameters, 1).standardUncertainty ?? 0, 6.15e6)).toBeLessThan(0.01)
    const chi = noisy.residuals.reduce(
      (s, x) => s + (x.residual / (x.kind === 'velocity' ? 3 : 5e6)) ** 2,
      0,
    )
    expect(rel(chi, noisy.chiSquare)).toBeLessThan(1e-9)
  })

  it('reports the correlation of a velocity-only ladder', () => {
    const r = fitPowder(load(0.38, 20e6), ladder(load(), 3, 0), { parameters: both })
    expect(Math.abs(r.correlation?.[0]?.[1] ?? 0)).toBeGreaterThan(0.99)
    expect(nth(r.parameters, 1).standardUncertainty).toBeGreaterThan(
      2 * (nth(noisy.parameters, 1).standardUncertainty ?? Infinity),
    )
    // apps/docs/docs/models/interior-powder-fit.md, "Identifiability": kappa 28.5
    expect(rel(r.conditionNumber, 28.5)).toBeLessThan(0.02)
  })

  it('recovers both parameters from a start above the truth', () => {
    const r = fitPowder(load(0.5, 45e6), ladder(load(), 3, 5e6), { parameters: both })
    expect(rel(nth(r.parameters, 0).value, 0.45)).toBeLessThan(1e-6)
    expect(rel(nth(r.parameters, 1).value, 30e6)).toBeLessThan(1e-6)
  })

  it('reports a start pressure driven to the floor as unresolved', () => {
    // from here the steps carry p_st into the flat region at the floor, where it has no effect
    const e = failure(() =>
      fitPowder(load(0.55, 45e6), ladder(load(), 3, 5e6), { parameters: both }),
    )
    expect(e.reason).toBe('unresolved')
    expect(e.unresolved).toEqual([1])
    expect(rel(e.estimate?.[1]?.value ?? 0, 5e6)).toBeLessThan(1e-3)
  })

  it('scales the covariance by the residual variance without sigmas', () => {
    const points = ladder(load(), 3, 0, 1)
    const plain = points.map(({ velocitySigma: _, ...x }) => x)
    const u = fitPowder(load(0.38), plain)
    const w = fitPowder(
      load(0.38),
      points.map((x) => ({ ...x, velocitySigma: 1 })),
    )
    const scale = Math.sqrt(u.chiSquare / u.degreesOfFreedom)
    expect(
      rel(
        nth(u.parameters, 0).standardUncertainty ?? 0,
        (nth(w.parameters, 0).standardUncertainty ?? 0) * scale,
      ),
    ).toBeLessThan(1e-6)
  })

  it('reports sigma 0 and a NaN correlation for an exact fit without sigmas', () => {
    const plain = ladder(load(), 0, 0)
    const r = fitPowder(load(), plain)
    expect(r.chiSquare).toBe(0)
    expect(nth(r.parameters, 0).standardUncertainty).toBe(0)
    expect(r.correlation?.[0]?.[0]).toBeNaN()
  })
})

describe('powder fit result', () => {
  it('applies the values and lists residuals in ladder order', () => {
    // pressures on the second and fourth point only
    const points = ladder(load(), 3, 10e6).map(({ peakPressure, pressureSigma, ...x }, i) =>
      i % 2 ? { ...x, peakPressure, pressureSigma } : x,
    )
    const twin = { ...nth(points, 2), muzzleVelocity: nth(points, 2).muzzleVelocity + 2 }
    const r = fitPowder(load(0.38), [...points, twin])
    expect(r.residuals.map((x) => `${x.kind} ${x.charge}`)).toEqual([
      'velocity 0.0026',
      'velocity 0.0027',
      'pressure 0.0027',
      'velocity 0.0028',
      'velocity 0.0029',
      'pressure 0.0029',
      'velocity 0.003',
      'velocity 0.0028',
    ])
    for (const x of r.residuals) expect(x.residual).toBe(x.predicted - x.observed)
    expect(r.runCount % charges.length).toBe(0)
    expect(r.chargeRange).toEqual({ min: 2.6e-3, max: 3e-3 })
    const base = load(0.38)
    expect(r.load).toEqual({
      ...base,
      propellant: {
        ...base.propellant,
        burn: { ...base.propellant.burn, vivacity: nth(r.parameters, 0).value },
      },
    })
    expect(r.load.charge).toBe(0.0028)
  })

  it('predicts at the fitted values when no step is accepted', () => {
    // start at the truth; floor + (p - floor) rounds to the next double above p
    const truth = { ...load(0.45, 41000001.48), ignitionPressure: 5000000.0548 }
    const points = ladder(truth, 3, 2e6)
    const r = fitPowder(truth, points, { parameters: ['burnRate', 'startPressure'] })
    // one step, not accepted: the burn coefficient stays exactly at its start
    expect([r.iterations, nth(r.parameters, 0).value]).toEqual([1, 0.45])
    expect(r.load.startPressure).not.toBe(truth.startPressure)
    for (const x of r.residuals) {
      const run = interior({ ...r.load, charge: x.charge })
      if (!run.valid) throw new Error(run.reason)
      expect(x.predicted).toBe(x.kind === 'velocity' ? run.muzzleVelocity : run.peakBreechPressure)
    }
    // chi-square of the reported predictions, not of the start values
    const sigma = (x: (typeof r.residuals)[number]) => {
      const point = points.find((p) => p.charge === x.charge)
      return x.kind === 'velocity' ? point?.velocitySigma : point?.pressureSigma
    }
    const chi = r.residuals.reduce(
      (s, x) => s + ((x.predicted - x.observed) / (sigma(x) ?? Number.NaN)) ** 2,
      0,
    )
    expect(r.chiSquare / chi).toBeCloseTo(1, 12)
    expect(r.chiSquare).toBeGreaterThan(0)
  })
})

describe('powder fit failures', () => {
  const both = ['burnRate', 'startPressure'] as const
  const points = ladder(load(), 3, 0)

  it('reports ill-conditioned ladders', () => {
    const same = failure(() =>
      fitPowder(
        load(0.38, 20e6),
        [nth(points, 2), { ...nth(points, 2), muzzleVelocity: nth(points, 2).muzzleVelocity + 3 }],
        {
          parameters: both,
        },
      ),
    )
    expect(same.reason).toBe('ill-conditioned')
    expect(same.conditionNumber).toBeGreaterThan(1e3)
    // both parameters raise the velocity and the column-scaled columns are equal, so the weak
    // direction is (1, -1)/sqrt(2) up to sign
    const direction = same.direction ?? []
    const d0 = nth(direction, 0)
    const d1 = nth(direction, 1)
    expect(same.direction).toHaveLength(2)
    expect(Math.abs(Math.abs(d0) - Math.SQRT1_2)).toBeLessThan(1e-6)
    expect(Math.abs(d0 + d1)).toBeLessThan(1e-6)
    expect(same.estimate).toHaveLength(2)
    const tight = failure(() =>
      fitPowder(load(0.38, 20e6), points, { parameters: both, maxCondition: 10 }),
    )
    expect(tight.reason).toBe('ill-conditioned')
  })

  it('reports each failure reason', () => {
    const broken = { ...load(), chamber: { ...load().chamber, volume: -1 } }
    const under = failure(() => fitPowder(broken, [nth(points, 0)], { parameters: both }))
    expect(under.reason).toBe('underdetermined')
    expect(under.message).toBe('powder fit: underdetermined')
    expect(under).toBeInstanceOf(InputError)

    // covolume times 3.5 g exceeds the 3.4 cm3 chamber
    const big = failure(() =>
      fitPowder(load(0.38), [...points, { ...nth(points, 4), charge: 3.5e-3 }]),
    )
    expect(big.reason).toBe('invalid')
    expect(big.charge).toBe(3.5e-3)
    expect(big.result?.reason).toBe('chamberVolume')

    const stuck = failure(() => fitPowder(load(0.2), points, { maxIterations: 1 }))
    expect(stuck.reason).toBe('not-converged')
    expect(stuck.estimate).toHaveLength(1)

    const slow = failure(() => fitPowder(load(0.38), points, { options: { maxTime: 1e-5 } }))
    expect(slow.reason).toBe('invalid')
    expect(slow.result?.reason).toBe('maxTime')
  })

  it('reports an invalid run inside a Jacobian with its charge and result', () => {
    // maxTime between the barrel times at 0.38 1/s and at the Jacobian's down-step, slowest charge
    const limit = (vivacity: number) => {
      let lo = 1e-3
      let hi = 3e-3
      for (let i = 0; i < 50; i++) {
        const mid = (lo + hi) / 2
        if (interior({ ...load(vivacity), charge: 2.6e-3 }, { maxTime: mid }).valid) hi = mid
        else lo = mid
      }
      return hi
    }
    const maxTime = (limit(0.38) + limit(0.38 * Math.exp(-1e-3))) / 2
    const e = failure(() => fitPowder(load(0.38), points, { options: { maxTime } }))
    expect(e.reason).toBe('invalid')
    expect(e.charge).toBe(2.6e-3)
    expect(e.result?.reason).toBe('maxTime')
    expect(e.estimate).toHaveLength(1)
  })

  it('rejects malformed inputs before any run', () => {
    const plain = (f: () => unknown) => {
      expect(f).toThrow(InputError)
      try {
        f()
      } catch (e) {
        expect(e).not.toBeInstanceOf(PowderFitError)
      }
    }
    const p = nth(points, 0)
    const { velocitySigma: _, ...bare } = p
    plain(() => fitPowder(load(), []))
    plain(() => fitPowder(load(), [{ ...p, charge: -1 }]))
    plain(() => fitPowder(load(), [{ ...p, muzzleVelocity: Number.NaN }]))
    plain(() => fitPowder(load(), [{ ...p, velocitySigma: 0 }]))
    plain(() => fitPowder(load(), [p, bare]))
    plain(() => fitPowder(load(), [{ ...p, peakPressure: 3e8 }]))
    plain(() => fitPowder(load(), [{ ...p, pressureSigma: 1e7 }]))
    plain(() => fitPowder(load(), [{ ...bare, peakPressure: 3e8, pressureSigma: 1e7 }]))
    plain(() => fitPowder(load(), [{ ...p, peakPressure: -3e8, pressureSigma: 1e7 }]))
    plain(() => fitPowder(load(), points, { parameters: [] }))
    // @ts-expect-error an unknown parameter name
    plain(() => fitPowder(load(), points, { parameters: ['exponent'] }))
    plain(() => fitPowder(load(), points, { parameters: ['burnRate', 'burnRate'] }))
    plain(() => fitPowder(load(), points, { maxIterations: 1.5 }))
    plain(() => fitPowder(load(), points, { maxCondition: 0 }))
    // start pressure below the floor max(p_i, p_f + p_e(0)): ignition, friction, engraving at travel 0
    plain(() => fitPowder(load(0.45, 4e6), points, { parameters: both }))
    const resisted = (resistance: InteriorLoad['resistance']) => ({
      ...load(0.45, 8e6),
      resistance,
    })
    plain(() => fitPowder(resisted({ friction: 10e6 }), points, { parameters: both }))
    plain(() =>
      fitPowder(resisted({ engraving: [{ travel: 0, pressure: 10e6 }] }), points, {
        parameters: both,
      }),
    )
  })
})

describe('powder fit prior and robust loss', () => {
  const both = ['burnRate', 'startPressure'] as const
  const priors = {
    burnRate: { value: 0.45, sigma: 0.3 },
    startPressure: { value: 30e6, sigma: 0.5 },
  }
  // 0.005 g apart: the velocities barely separate the two parameters
  const narrow = ladder(load(), 3, 0)
    .slice(1, 3)
    .map((x, i) => ({ ...x, charge: 2.8e-3 + i * 5e-6 }))
  const narrowTruth = narrow.map((x) => {
    const r = interior({ ...load(), charge: x.charge })
    if (!r.valid) throw new Error(r.reason)
    return { ...x, muzzleVelocity: r.muzzleVelocity }
  })

  it('fits a two-charge velocity ladder with a prior and reports its uncertainty', () => {
    const e = failure(() => fitPowder(load(0.38, 20e6), narrowTruth, { parameters: both }))
    expect(e.reason).toBe('ill-conditioned')
    const r = fitPowder(load(0.38, 20e6), narrowTruth, { parameters: both, priors })
    expect(r.degreesOfFreedom).toBe(0)
    expect(rel(nth(r.parameters, 0).value, 0.45)).toBeLessThan(1e-3)
    expect(nth(r.parameters, 0).standardUncertainty).toBeGreaterThan(0)
    expect(nth(r.parameters, 0).standardUncertainty).toBeLessThan(0.3 * 0.45)
    expect(nth(r.parameters, 1).standardUncertainty).toBeGreaterThan(0)
    expect(r.priorChiSquare).toBeLessThan(1e-6)
  })

  it('matches the fit without a prior under a very wide prior', () => {
    const points = ladder(load(), 3, 5e6, 1)
    const plain = fitPowder(load(0.38, 20e6), points, { parameters: both })
    const wide = fitPowder(load(0.38, 20e6), points, {
      parameters: both,
      priors: { burnRate: { value: 0.1, sigma: 1e5 }, startPressure: { value: 9e6, sigma: 1e5 } },
    })
    plain.parameters.forEach((p, k) => {
      expect(rel(nth(wide.parameters, k).value, p.value)).toBeLessThan(1e-6)
      expect(
        rel(nth(wide.parameters, k).standardUncertainty ?? 0, p.standardUncertainty ?? 1),
      ).toBeLessThan(1e-6)
    })
    expect(rel(wide.chiSquare, plain.chiSquare)).toBeLessThan(1e-6)
  })

  it('splits chi-square into the data and the prior', () => {
    const points = ladder(load(), 3, 0, 1)
    const r = fitPowder(load(0.38), points, { priors: { burnRate: { value: 0.3, sigma: 0.2 } } })
    expect(r.priorChiSquare).toBeGreaterThan(0)
    expect(r.dataChiSquare + r.priorChiSquare).toBeCloseTo(r.chiSquare, 9)
    expect(r.loss).toBe(r.chiSquare)
    const none = fitPowder(load(0.38), points)
    expect([none.priorChiSquare, none.dataChiSquare]).toEqual([0, none.chiSquare])
    // a prior pulls the fit toward its centre
    expect(Math.abs(Math.log(nth(r.parameters, 0).value / 0.3))).toBeLessThan(
      Math.abs(Math.log(nth(none.parameters, 0).value / 0.3)),
    )
  })

  it('limits the pull of a string 5 sigma off with the Huber loss', () => {
    const points = ladder(load(), 3, 0)
    const bad = points.map((x, i) =>
      i === 2 ? { ...x, muzzleVelocity: x.muzzleVelocity + 15 } : x,
    )
    const error = (r: { parameters: { value: number }[] }) =>
      Math.abs(Math.log(nth(r.parameters, 0).value / 0.45))
    const plain = fitPowder(load(0.38), bad)
    const robust = fitPowder(load(0.38), bad, { huberThreshold: 1.5 })
    expect(error(robust)).toBeLessThan(error(plain))
    expect(robust.loss).toBeLessThan(robust.chiSquare)
    expect(robust.dataChiSquare).toBeGreaterThanOrEqual(plain.dataChiSquare)
    // a threshold above every residual is the quadratic loss
    const loose = fitPowder(load(0.38), bad, { huberThreshold: 100 })
    expect(nth(loose.parameters, 0).value).toBe(nth(plain.parameters, 0).value)
  })

  it('rejects malformed priors and a Huber loss without sigmas', () => {
    const points = ladder(load(), 3, 0)
    const bare = points.map(({ velocitySigma: _, ...x }) => x)
    const prior = { burnRate: { value: 0.45, sigma: 0.3 } }
    expect(() => fitPowder(load(), bare, { priors: prior })).toThrow(InputError)
    expect(() => fitPowder(load(), bare, { huberThreshold: 2 })).toThrow(InputError)
    expect(() => fitPowder(load(), points, { huberThreshold: 0 })).toThrow(InputError)
    expect(() =>
      fitPowder(load(), points, { priors: { burnRate: { value: -1, sigma: 1 } } }),
    ).toThrow(InputError)
    expect(() =>
      fitPowder(load(), points, { priors: { burnRate: { value: 1, sigma: 0 } } }),
    ).toThrow(InputError)
    expect(() => fitPowder(load(), points, { priors: { burnRate: undefined } })).not.toThrow()
    // the start pressure is not fitted
    expect(() =>
      fitPowder(load(), points, { priors: { startPressure: { value: 30e6, sigma: 1 } } }),
    ).toThrow(InputError)
    expect(() =>
      fitPowder(load(0.38, 20e6), points, {
        parameters: both,
        priors: { startPressure: { value: 4e6, sigma: 1 } },
      }),
    ).toThrow(InputError)
  })
})

describe('powder fit prediction bands', () => {
  const truth = load()
  const parameters = ['burnRate', 'startPressure'] as const

  it('covers the true value at held-out charges in 85 to 95 % of noisy repeats', () => {
    // coarser integration than the default keeps 1000 fits quick; the true values use it too
    const coarse = { relativeTolerance: 1e-8, absoluteTolerance: 1e-10, outputStep: 1e-5 }
    const truthAt = (charge: number) => {
      const r = interior({ ...truth, charge }, coarse)
      if (!r.valid) throw new Error(r.reason)
      return r
    }
    const rows = [2.6e-3, 2.8e-3, 3e-3].map((charge) => ({ charge, ...truthAt(charge) }))
    // inside the fired range, and just above it (an extrapolation)
    const held = [2.7e-3, 3.1e-3].map((charge) => ({ charge, ...truthAt(charge) }))
    const covered = held.map(() => ({ velocity: 0, pressure: 0 }))
    const draw = normals(58)
    const repeats = 1000
    for (let n = 0; n < repeats; n++) {
      const noisy = rows.map((r) => ({
        charge: r.charge,
        muzzleVelocity: r.muzzleVelocity + 3 * draw(),
        velocitySigma: 3,
      }))
      const fit = fitPowder(load(0.43), noisy, { options: coarse })
      held.forEach((t, i) => {
        const p = predictPowder(fit, t.charge, { options: coarse })
        if (p.velocity.lower <= t.muzzleVelocity && t.muzzleVelocity <= p.velocity.upper)
          nth(covered, i).velocity++
        if (p.pressure.lower <= t.peakBreechPressure && t.peakBreechPressure <= p.pressure.upper)
          nth(covered, i).pressure++
      })
    }
    for (const c of covered) {
      expect(c.velocity / repeats).toBeGreaterThan(0.85)
      expect(c.velocity / repeats).toBeLessThan(0.95)
      expect(c.pressure / repeats).toBeGreaterThan(0.85)
      expect(c.pressure / repeats).toBeLessThan(0.95)
    }
  }, 360_000)

  it('is wider outside the fired range than at its centre and marks the extrapolation', () => {
    const fit = fitPowder(load(0.4), ladder(truth, 3, 2e6, 1), { parameters: [...parameters] })
    const centre = predictPowder(fit, 2.8e-3)
    const below = predictPowder(fit, 2.4e-3)
    const above = predictPowder(fit, 3.2e-3)
    expect(centre.extrapolation).toBeUndefined()
    expect(predictPowder(fit, 2.6e-3).extrapolation).toBeUndefined()
    expect(predictPowder(fit, 3e-3).extrapolation).toBeUndefined()
    expect(below.extrapolation).toBe('below')
    expect(above.extrapolation).toBe('above')
    for (const outside of [below, above]) {
      expect(outside.velocity.standardUncertainty).toBeGreaterThan(
        centre.velocity.standardUncertainty,
      )
      expect(outside.pressure.standardUncertainty).toBeGreaterThan(
        centre.pressure.standardUncertainty,
      )
    }
    // farther out is wider still
    expect(predictPowder(fit, 3.3e-3).pressure.standardUncertainty).toBeGreaterThan(
      above.pressure.standardUncertainty,
    )
    expect(predictPowder(fit, 2.2e-3).velocity.standardUncertainty).toBeGreaterThan(
      below.velocity.standardUncertainty,
    )
  })

  it('returns the model value, a symmetric interval and the chosen coverage', () => {
    const fit = fitPowder(load(0.4), ladder(truth, 3, 2e6, 1), { parameters: [...parameters] })
    const p = predictPowder(fit, 2.85e-3)
    const r = interior({ ...fit.load, charge: 2.85e-3 })
    if (!r.valid) throw new Error(r.reason)
    expect(p.velocity.value).toBe(r.muzzleVelocity)
    expect(p.pressure.value).toBe(r.peakBreechPressure)
    expect(p.velocity.value - p.velocity.lower).toBeCloseTo(p.velocity.upper - p.velocity.value, 9)
    expect(p.level).toBe(0.9)
    // 90 % of a normal: 1.645 standard uncertainties
    expect((p.velocity.upper - p.velocity.value) / p.velocity.standardUncertainty).toBeCloseTo(
      1.6449,
      3,
    )
    const wide = predictPowder(fit, 2.85e-3, { level: 0.99 })
    expect(wide.velocity.upper - wide.velocity.lower).toBeGreaterThan(
      p.velocity.upper - p.velocity.lower,
    )
    expect(wide.velocity.standardUncertainty).toBe(p.velocity.standardUncertainty)
  })

  it('uses the Student quantile when the ladder has no uncertainties', () => {
    const fit = fitPowder(load(0.4), ladder(truth, 0, 0, 0.5))
    expect(fit.weighted).toBe(false)
    const p = predictPowder(fit, 2.8e-3)
    // four degrees of freedom: the 90 % quantile is 2.132, above the normal 1.645
    expect((p.velocity.upper - p.velocity.value) / p.velocity.standardUncertainty).toBeCloseTo(
      2.1318,
      3,
    )
  })

  it('refuses a fit without covariance, a bad charge or level, and an invalid run', () => {
    const rows = ladder(truth, 0, 0).slice(0, 1)
    const exact = fitPowder(load(0.4), rows)
    expect(exact.covariance).toBeUndefined()
    expect(() => predictPowder(exact, 2.8e-3)).toThrow(InputError)
    const fit = fitPowder(load(0.4), ladder(truth, 3, 0))
    expect(() => predictPowder(fit, 0)).toThrow(InputError)
    expect(() => predictPowder(fit, 2.8e-3, { level: 1 })).toThrow(InputError)
    const e = failure(() => predictPowder(fit, 3.6e-3))
    expect(e.reason).toBe('invalid')
    expect(e.charge).toBe(3.6e-3)
  })
})
