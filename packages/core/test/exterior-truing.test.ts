import { describe, expect, it } from 'vitest'
import {
  airDensity,
  dragCoefficient,
  dragTables,
  InputError,
  lbPerSqInToKgPerSqM,
  type Observation,
  standardAtmosphere,
  type TrajectoryInput,
  TruingError,
  type TruingSession,
  trajectory,
  trueDrag,
  trueDragSessions,
  trueMuzzleVelocity,
} from '../src/index.ts'

const g = 9.80665
const g7 = {
  kind: 'bc' as const,
  model: 'G7' as const,
  bands: [{ ballisticCoefficient: 0.3 * lbPerSqInToKgPerSqM, minVelocity: 0 }],
}
const flat = (cd: number) => ({
  kind: 'curve' as const,
  curve: [
    [0, cd],
    [10, cd],
  ] as const,
})
const base: TrajectoryInput = {
  projectile: { mass: 0.01134, diameter: 0.00782, length: 0.0312, drag: g7 },
  muzzleVelocity: 790,
  firearm: { sightHeight: 0.05 },
  air: standardAtmosphere(0),
  zero: { elevationAngle: 0.004, windageAngle: 0 },
}
const tight = { relativeTolerance: 1e-10, absoluteTolerance: 1e-9 }
/** The shot with muzzle velocity times `v` and drag times `k`. */
const scaled = (shot: TrajectoryInput, v: number, k: number): TrajectoryInput => ({
  ...shot,
  muzzleVelocity: shot.muzzleVelocity * v,
  projectile: {
    ...shot.projectile,
    drag: {
      ...g7,
      bands: [{ ballisticCoefficient: g7.bands[0].ballisticCoefficient / k, minVelocity: 0 }],
    },
  },
})
/** Observations of the given kinds generated by the solver. */
const observe = (
  shot: TrajectoryInput,
  list: [Observation['kind'], number, number?][],
  options = {},
) => {
  const t = trajectory(
    shot,
    list.map((x) => x[1]),
    { ...tight, ...options },
  )
  return list.map(([kind, range, sigma]): Observation => {
    const p = t.points.find((q) => q.range === range)
    if (!p) throw new Error(`range ${range}`)
    return {
      kind,
      range,
      value: p[kind],
      ...(sigma === undefined ? {} : { standardUncertainty: sigma }),
    }
  })
}
const mixed: [Observation['kind'], number, number][] = [
  ['height', 300, 0.01],
  ['height', 600, 0.01],
  ['height', 700, 0.01],
  ['velocity', 800, 1],
]

describe('truing round trips', () => {
  it('recovers muzzle velocity and drag factor at fixed bore angles', () => {
    const obs = observe(scaled(base, 1.02, 0.95), mixed)
    const r = trueDrag(base, obs, { fitMuzzleVelocity: true })
    expect(r.parameters.map((p) => p.name)).toEqual(['muzzleVelocity', 'dragFactor'])
    expect(Math.abs(r.parameters[0].value / (790 * 1.02) - 1)).toBeLessThan(1e-6)
    expect(Math.abs(r.parameters[1].value / 0.95 - 1)).toBeLessThan(1e-6)
    expect(r.parameters[0].initial).toBe(790)
    expect(r.shot.muzzleVelocity).toBe(r.parameters[0].value)
    for (const x of r.residuals) expect(Math.abs(x.residual)).toBeLessThan(1e-6)
    expect(r.degreesOfFreedom).toBe(2)
    expect(r.residuals[3].mach).toBeGreaterThan(1)
  })

  it('re-zeroes every candidate when the shot has a zero range', () => {
    const zeroed = { ...base, zero: { range: 100 } }
    const obs = observe(scaled(zeroed, 1.02, 0.95), mixed)
    const r = trueDrag(zeroed, obs, { fitMuzzleVelocity: true })
    expect(Math.abs(r.parameters[0].value / (790 * 1.02) - 1)).toBeLessThan(1e-4)
    expect(Math.abs(r.parameters[1].value / 0.95 - 1)).toBeLessThan(1e-4)
    // holding the bore of the nominal zero instead biases the fit
    const held = { ...base, zero: trajectory(zeroed, [100]).bore }
    const biased = trueDrag(held, obs, { fitMuzzleVelocity: true })
    expect(Math.abs(biased.parameters[0].value / (790 * 1.02) - 1)).toBeGreaterThan(1e-3)
  })

  it('fits the modified point mass', () => {
    const shot: TrajectoryInput = {
      ...base,
      projectile: { ...base.projectile, aerodynamics: { liftSlope: 2.6, momentSlope: 2.8 } },
      firearm: { sightHeight: 0.05, twist: 0.254, twistHand: 'right' },
    }
    const model = { model: 'modified-point-mass' as const }
    const obs = observe(
      { ...shot, muzzleVelocity: 800 },
      [
        ['height', 400],
        ['height', 800],
      ],
      model,
    )
    const r = trueMuzzleVelocity(shot, obs, model)
    expect(Math.abs(r.parameters[0].value / 800 - 1)).toBeLessThan(1e-6)
  })
})

describe('truing closed forms', () => {
  it('solves the vacuum parabola for the muzzle velocity', () => {
    const e = 0.01
    const hs = 0.05
    const s = 500
    const h = -0.4
    const shot: TrajectoryInput = {
      ...base,
      projectile: { ...base.projectile, drag: flat(0) },
      zero: { elevationAngle: e, windageAngle: 0 },
    }
    const expected = Math.sqrt((g * s ** 2) / (2 * Math.cos(e) ** 2 * (s * Math.tan(e) - hs - h)))
    const r = trueMuzzleVelocity(shot, [{ kind: 'height', range: s, value: h }], {
      coriolis: false,
    })
    expect(Math.abs(r.parameters[0].value / expected - 1)).toBeLessThan(1e-9)
    expect(r.parameters[0].standardUncertainty).toBeUndefined()
    expect(r.correlation).toBeUndefined()
    expect(r.degreesOfFreedom).toBe(0)
  })

  const oneD = (cd: number): TrajectoryInput => ({
    ...base,
    projectile: { ...base.projectile, drag: flat(cd) },
    firearm: { sightHeight: 0 },
    zero: { elevationAngle: 0, windageAngle: 0 },
  })
  const opts = { gravity: 0, coriolis: false }
  const k = (airDensity(base.air) * 0.3 * Math.PI * 0.00782 ** 2) / (8 * 0.01134)

  it('gives the drag factor of two velocities in one dimension', () => {
    const obs: Observation[] = [200, 700].map((x) => ({
      kind: 'velocity',
      range: x,
      value: 790 * Math.exp(-1.1 * k * x),
    }))
    const r = trueDrag(oneD(0.3), obs, {}, opts)
    expect(Math.abs(r.parameters[0].value / 1.1 - 1)).toBeLessThan(1e-8)
  })

  it('agrees with the weighted regression of ln v on distance', () => {
    const xs = [100, 300, 500, 700, 900]
    const noise = [1.5, -2, 0.5, 2.5, -1]
    const sigma = 2
    const obs: Observation[] = xs.map((x, i) => ({
      kind: 'velocity',
      range: x,
      value: 790 * Math.exp(-1.1 * k * x) + noise[i],
      standardUncertainty: sigma,
    }))
    const r = trueDrag(oneD(0.3), obs, {}, opts)
    // ln v = ln v0 - f k x with weights v^2 / sigma^2
    const w = obs.map((o) => o.value ** 2 / sigma ** 2)
    const sxx = xs.reduce((s, x, i) => s + w[i] * x * x, 0)
    const sxy = xs.reduce((s, x, i) => s + w[i] * x * (Math.log(790) - Math.log(obs[i].value)), 0)
    const f = sxy / (k * sxx)
    const sf = 1 / (k * Math.sqrt(sxx))
    expect(Math.abs(r.parameters[0].value / f - 1)).toBeLessThan(1e-3)
    expect(Math.abs((r.parameters[0].standardUncertainty ?? 0) / sf - 1)).toBeLessThan(1e-3)
  })

  it('gives the closed-form sigma of noise-free velocities', () => {
    const xs = [100, 300, 500, 700, 900]
    const sigma = 2
    const v = xs.map((x) => 790 * Math.exp(-1.1 * k * x))
    const obs = xs.map(
      (x, i): Observation => ({
        kind: 'velocity',
        range: x,
        value: v[i],
        standardUncertainty: sigma,
      }),
    )
    const r = trueDrag(oneD(0.3), obs, {}, opts)
    // dv/d(ln f) = -f k x v, so sigma_f = 1 / (k sqrt(sum x^2 v^2 / sigma^2))
    const sf = 1 / (k * Math.sqrt(xs.reduce((s, x, i) => s + (x * v[i]) ** 2, 0) / sigma ** 2))
    expect(Math.abs((r.parameters[0].standardUncertainty ?? 0) / sf - 1)).toBeLessThan(1e-6)
  })
})

describe('truing uncertainty', () => {
  const noisy = () => {
    const obs = observe(scaled(base, 1.02, 0.95), [
      ['height', 300],
      ['height', 500],
      ['height', 700],
      ['height', 900],
    ])
    return obs.map((o, i) => ({ ...o, value: o.value + [0.004, -0.006, 0.003, 0.005][i] }))
  }

  it('scales the covariance by the residual variance without sigmas', () => {
    const obs = noisy()
    const u = trueDrag(base, obs, { fitMuzzleVelocity: true })
    const w = trueDrag(
      base,
      obs.map((o) => ({ ...o, standardUncertainty: 1 })),
      { fitMuzzleVelocity: true },
    )
    const scale = Math.sqrt(u.chiSquare / u.degreesOfFreedom)
    for (let j = 0; j < 2; j++)
      expect(
        Math.abs(
          (u.parameters[j].standardUncertainty ?? 0) /
            ((w.parameters[j].standardUncertainty ?? 0) * scale) -
            1,
        ),
      ).toBeLessThan(1e-6)
  })

  it('stops at a minimum of chi-square', () => {
    // far from the initial values and with large residuals, so the fit needs several steps
    const obs = observe(scaled(base, 1.1, 0.8), [
      ['height', 300],
      ['height', 500],
      ['height', 700],
      ['height', 900],
    ]).map((o, i) => ({ ...o, value: o.value + [0.04, -0.06, 0.03, 0.05][i] }))
    const r = trueDrag(base, obs, { fitMuzzleVelocity: true })
    const [v, f] = r.parameters.map((p) => p.value)
    const chi = (dv: number, df: number) => {
      const t = trajectory(
        scaled(base, (v * dv) / 790, f * df),
        obs.map((o) => o.range),
        tight,
      )
      return obs.reduce((s, o, i) => s + (t.points[i][o.kind] - o.value) ** 2, 0)
    }
    expect(Math.abs(chi(1, 1) / r.chiSquare - 1)).toBeLessThan(1e-9)
    for (const e of [1 + 1e-4, 1 - 1e-4]) {
      expect(chi(e, 1)).toBeGreaterThan(r.chiSquare)
      expect(chi(1, e)).toBeGreaterThan(r.chiSquare)
    }
  })

  it('reads the condition number as the correlation of two parameters', () => {
    const r = trueDrag(base, noisy(), { fitMuzzleVelocity: true })
    const rho = Math.abs(r.correlation?.[0][1] ?? 0)
    expect(rho).toBeGreaterThan(0.5)
    expect(Math.abs(r.conditionNumber ** 2 / ((1 + rho) / (1 - rho)) - 1)).toBeLessThan(1e-9)
    expect(r.correlation?.[0][0]).toBeCloseTo(1, 12)
  })

  it('fits elevation holds like the corresponding heights', () => {
    const truth = scaled(base, 1.02, 0.95)
    const holds = observe(truth, [
      ['elevationHold', 400],
      ['elevationHold', 800],
    ])
    const heights = holds.map(
      (o): Observation => ({
        kind: 'height',
        range: o.range,
        value: -o.range * Math.tan(o.value),
      }),
    )
    const a = trueDrag(base, holds, { fitMuzzleVelocity: true })
    const b = trueDrag(base, heights, { fitMuzzleVelocity: true })
    for (let j = 0; j < 2; j++)
      expect(Math.abs(a.parameters[j].value / b.parameters[j].value - 1)).toBeLessThan(1e-8)
  })
})

describe('Mach-dependent drag factor', () => {
  it('recovers a constant factor at every knot', () => {
    const truth = scaled(base, 1, 0.95)
    const obs = observe(
      truth,
      [200, 400, 600, 800, 1000, 1200].map((x): [Observation['kind'], number] => ['velocity', x]),
    )
    const r = trueDrag(base, obs, { knots: [1.5, 2] })
    expect(r.parameters.map((p) => p.mach)).toEqual([1.5, 2])
    for (const p of r.parameters) expect(Math.abs(p.value / 0.95 - 1)).toBeLessThan(1e-5)
    expect(r.shot.projectile.drag.kind).toBe('curve')
    expect(Object.keys(r.shot.projectile.drag)).toEqual(['kind', 'curve'])
  })

  it('recovers a factor that varies between the knots', () => {
    const knots = [1.2, 1.8, 2.3]
    const factors = [0.9, 1.05, 0.97]
    const factor = knots.map((m, i) => [m, factors[i]] as const)
    const bc = g7.bands[0].ballisticCoefficient
    // truth on the union of the G7 nodes and the knots
    const nodes = [...new Set([...dragTables.G7.map((n) => n[0]), ...knots])].sort((a, b) => a - b)
    const curve = nodes.map(
      (m) =>
        [
          m,
          (dragCoefficient(factor, m) * dragCoefficient(dragTables.G7, m) * 0.01134) /
            (bc * 0.00782 ** 2),
        ] as const,
    )
    const truth: TrajectoryInput = {
      ...base,
      projectile: { ...base.projectile, drag: { kind: 'curve', curve } },
    }
    const obs = observe(
      truth,
      [0, 100, 200, 300, 400, 500, 600, 700, 800, 900, 1000].map(
        (x): [Observation['kind'], number] => ['velocity', x],
      ),
    )
    const r = trueDrag(base, obs, { knots })
    r.parameters.forEach((p, i) => {
      expect(Math.abs(p.value / factors[i] - 1)).toBeLessThan(1e-6)
    })
  })

  it('drops a base node one ulp from a knot', () => {
    /** 2.15 moved by d units in the last place. */
    const ulp = (d: bigint) => {
      const b = new Float64Array([2.15])
      new BigInt64Array(b.buffer)[0] += d
      return b[0]
    }
    const bc = 0.5 * lbPerSqInToKgPerSqM
    const o = { coriolis: false, spinDrift: false, jump: false }
    for (const [knots, interpolation] of [1n, -1n].flatMap((d) =>
      (['linear', 'monotone-cubic'] as const).map((i): [number[], typeof i] => [[ulp(d), 2.6], i]),
    )) {
      const shot = (k: number): TrajectoryInput => ({
        projectile: {
          mass: 0.01134,
          diameter: 0.00782,
          drag: {
            kind: 'bc',
            model: 'G1',
            bands: [{ ballisticCoefficient: bc / k, minVelocity: 0 }],
            interpolation,
          },
        },
        muzzleVelocity: 850,
        firearm: { sightHeight: 0.04 },
        air: standardAtmosphere(0, 0),
        zero: { elevationAngle: 0.002, windageAngle: 0 },
      })
      const obs = observe(
        shot(0.95),
        [0, 100, 200, 300, 400, 500, 600, 700, 800, 900, 1000].map(
          (x): [Observation['kind'], number] => ['velocity', x],
        ),
        o,
      )
      const r = trueDrag(shot(1), obs, { knots }, o)
      for (const p of r.parameters) expect(Math.abs(p.value / 0.95 - 1)).toBeLessThan(1e-8)
      const drag = r.shot.projectile.drag
      const nodes = drag.kind === 'curve' ? drag.curve.map((n) => n[0]) : []
      expect(nodes).toContain(knots[0])
      expect(nodes).not.toContain(2.15)
    }
  })
})

describe('truing with the monotone cubic', () => {
  const velocities = [200, 400, 600, 800, 1000, 1200].map((x): [Observation['kind'], number] => [
    'velocity',
    x,
  ])
  const withDrag = (
    shot: TrajectoryInput,
    drag: TrajectoryInput['projectile']['drag'],
  ): TrajectoryInput => ({
    ...shot,
    projectile: { ...shot.projectile, drag },
  })
  const bc = g7.bands[0].ballisticCoefficient
  const i = 0.01134 / (bc * 0.00782 ** 2)
  const cubicBc = { ...g7, interpolation: 'monotone-cubic' as const }
  const cubicCurve = (k: number) => ({
    kind: 'curve' as const,
    curve: dragTables.G7.map(([m, c]) => [m, i * k * c] as const),
    interpolation: 'monotone-cubic' as const,
  })

  it('keeps the interpolation in the constant-factor fit', () => {
    const obs = observe(withDrag(base, cubicCurve(1.03)), velocities)
    const r = trueDrag(withDrag(base, cubicCurve(1)), obs)
    expect(Math.abs(r.parameters[0].value / 1.03 - 1)).toBeLessThan(1e-6)
    const slower = { ...cubicBc, bands: [{ ballisticCoefficient: bc / 1.03, minVelocity: 0 }] }
    const b = trueDrag(withDrag(base, cubicBc), observe(withDrag(base, slower), velocities))
    expect(Math.abs(b.parameters[0].value / 1.03 - 1)).toBeLessThan(1e-6)
  })

  it('keeps the interpolation in the knot fit', () => {
    // knots on G7 nodes: the curve built from factor 1 is the BC's cubic
    const obs = observe(
      withDrag(base, { ...cubicBc, bands: [{ ballisticCoefficient: bc / 0.95, minVelocity: 0 }] }),
      velocities,
    )
    const r = trueDrag(withDrag(base, cubicBc), obs, { knots: [1.5, 2] })
    for (const p of r.parameters) expect(Math.abs(p.value / 0.95 - 1)).toBeLessThan(1e-5)
    expect(r.shot.projectile.drag).toMatchObject({ kind: 'curve', interpolation: 'monotone-cubic' })
  })

  it('reads the own coefficient with the cubic at a knot between base nodes', () => {
    // knot 0.93 lies between G7 nodes and changes the neighbouring slopes of the cubic, so the fit
    // on the BC's own observations returns factors slightly off 1
    // (`apps/docs/docs/models/exterior-drag.md`, "Monotone cubic interpolation")
    const obs = observe(withDrag(base, cubicBc), velocities)
    const knots = [0.93, 1.5, 2]
    const at = (shot: TrajectoryInput, m: number) => {
      const drag = shot.projectile.drag
      return drag.kind === 'curve' ? (drag.curve.find((n) => n[0] === m)?.[1] ?? NaN) : NaN
    }
    const own = (m: number) => i * dragCoefficient(dragTables.G7, m, 'monotone-cubic')
    const r = trueDrag(withDrag(base, cubicBc), obs, { knots })
    const f = r.parameters.map((p) => p.value)
    for (const x of f) expect(Math.abs(x - 1)).toBeLessThan(2e-4)
    for (const x of r.residuals) expect(Math.abs(x.residual)).toBeLessThan(5e-3)
    expect(Math.abs(at(r.shot, 0.93) / (f[0] * own(0.93)) - 1)).toBeLessThan(1e-14)
    // the factor stays linear between knots: base node 1.2 lies between the knots 0.93 and 1.5
    const linear = f[0] + ((f[1] - f[0]) * (1.2 - 0.93)) / (1.5 - 0.93)
    expect(Math.abs(at(r.shot, 1.2) / (linear * own(1.2)) - 1)).toBeLessThan(1e-13)
    const c = cubicCurve(1)
    const rc = trueDrag(withDrag(base, c), obs, { knots })
    const own0 = dragCoefficient(c.curve, 0.93, 'monotone-cubic')
    expect(Math.abs(at(rc.shot, 0.93) / (rc.parameters[0].value * own0) - 1)).toBeLessThan(1e-14)
  })
})

describe('truing failures', () => {
  const reason = (f: () => unknown) => {
    try {
      f()
    } catch (e) {
      if (e instanceof TruingError) return e
      throw e
    }
    throw new Error('no error')
  }

  it('reports each failure reason', () => {
    const h = (range: number, value = -0.1): Observation => ({ kind: 'height', range, value })
    expect(reason(() => trueDrag(base, [h(300)], { fitMuzzleVelocity: true })).reason).toBe(
      'underdetermined',
    )
    const zero = reason(() => trueDrag({ ...base, zero: { range: 100 } }, [h(100, 0)]))
    expect(zero.reason).toBe('unresolved')
    expect(zero.unresolved).toEqual([0])
    // both knots above the flight's Mach numbers: the lower acts as a constant factor
    const slow = { ...base, muzzleVelocity: 500 }
    const v = (range: number, value: number): Observation => ({ kind: 'velocity', range, value })
    const knots = reason(() => trueDrag(slow, [v(200, 450), v(400, 410)], { knots: [2, 2.5] }))
    expect(knots.reason).toBe('unresolved')
    expect(knots.unresolved).toEqual([1])
    const same = reason(() => trueDrag(base, [h(300), h(300, -0.11)], { fitMuzzleVelocity: true }))
    expect(same.reason).toBe('ill-conditioned')
    expect(same.conditionNumber).toBeGreaterThan(1e3)
    expect(same.direction).toHaveLength(2)
    const steep = { ...base, lookAngle: Math.PI / 2, zero: { elevationAngle: 0, windageAngle: 0 } }
    expect(reason(() => trueMuzzleVelocity(steep, [h(50000)])).reason).toBe('unreachable')
    const stuck = reason(() =>
      trueDrag(
        base,
        observe(scaled(base, 1.02, 0.95), mixed),
        { fitMuzzleVelocity: true },
        { maxIterations: 1 },
      ),
    )
    expect(stuck.reason).toBe('not-converged')
    expect(stuck.estimate).toHaveLength(2)
    expect(stuck).toBeInstanceOf(InputError)
  })

  it('fails with step-budget when the fit uses up maxTotalSteps', () => {
    const zeroed = { ...base, zero: { range: 100 } }
    const obs = observe(scaled(zeroed, 1.02, 0.95), mixed)
    const free = trueDrag(zeroed, obs, { fitMuzzleVelocity: true })
    // the total covers the zero searches: more than the main runs of all trajectories
    expect(free.steps).toBeGreaterThan(
      free.trajectoryCount * trajectory(zeroed, [800], tight).steps,
    )
    const exact = trueDrag(zeroed, obs, { fitMuzzleVelocity: true }, { maxTotalSteps: free.steps })
    expect(exact).toEqual(free)
    const short = reason(() =>
      trueDrag(zeroed, obs, { fitMuzzleVelocity: true }, { maxTotalSteps: free.steps - 1 }),
    )
    expect(short.reason).toBe('step-budget')
    expect(short.message).toBe('truing: step-budget')
    expect(short.estimate).toHaveLength(2)
    const one: Observation[] = [{ kind: 'height', range: 300, value: -0.1 }]
    // @ts-expect-error the fit sets its own budget from maxTotalSteps
    expect(trueMuzzleVelocity(base, one, { budget: { used: 0, max: 1 } }).steps).toBeGreaterThan(1)
  })

  it('passes on an error that is not an InputError from a later trajectory', () => {
    // every trajectory spreads the shot: the second read of wind throws as a defect would
    let reads = 0
    const faulty: TrajectoryInput = {
      ...base,
      get wind() {
        reads++
        if (reads > 1) throw new TypeError('defect')
        return base.wind
      },
    }
    const one: Observation[] = [{ kind: 'height', range: 300, value: -0.1 }]
    expect(() => trueMuzzleVelocity(faulty, one)).toThrow(TypeError)
    expect(reads).toBe(2)
  })

  it('rejects malformed inputs before any trajectory', () => {
    const plain = (f: () => unknown) => {
      expect(f).toThrow(InputError)
      try {
        f()
      } catch (e) {
        expect(e).not.toBeInstanceOf(TruingError)
      }
    }
    const h: Observation = { kind: 'height', range: 300, value: -0.1 }
    const v: Observation = { kind: 'velocity', range: 300, value: 700 }
    plain(() => trueMuzzleVelocity(base, [{ ...h, standardUncertainty: 0 }]))
    plain(() => trueMuzzleVelocity(base, [{ ...h, standardUncertainty: 1 }, v]))
    plain(() => trueMuzzleVelocity(base, [h, v]))
    plain(() => trueMuzzleVelocity(base, [{ ...h, range: 0 }]))
    plain(() => trueMuzzleVelocity(base, []))
    for (const maxTotalSteps of [Number.NaN, 0, -1])
      plain(() => trueMuzzleVelocity(base, [h], { maxTotalSteps }))
    plain(() => trueDrag(base, [v, v], { knots: [2, 1.5] }))
    const banded = {
      ...base,
      projectile: {
        ...base.projectile,
        drag: {
          ...g7,
          bands: [
            g7.bands[0],
            { ballisticCoefficient: 0.2 * lbPerSqInToKgPerSqM, minVelocity: 600 },
          ],
        },
      },
    }
    plain(() => trueDrag(banded, [v, v], { knots: [1.5, 2] }))
    const misspelled = { ...base.projectile, drag: { ...g7, reference: 'Metro' as 'metro' } }
    plain(() => trueDrag({ ...base, projectile: misspelled }, [v, v], { knots: [1.5, 2] }))
  })
})

describe('several sessions', () => {
  const { projectile } = base
  const first: TruingSession['shot'] = {
    muzzleVelocity: 790,
    firearm: { sightHeight: 0.05 },
    air: standardAtmosphere(0),
    zero: { range: 100 },
  }
  const second: TruingSession['shot'] = {
    muzzleVelocity: 805,
    firearm: { sightHeight: 0.05 },
    air: { ...standardAtmosphere(1500), temperature: 268.15 },
    wind: [{ endDistance: Infinity, speed: 4, fromDirection: 0.5 }],
    zero: { range: 100 },
  }
  const three: [Observation['kind'], number, number][] = [
    ['height', 300, 0.01],
    ['height', 600, 0.01],
    ['velocity', 800, 1],
  ]
  const o1 = observe(scaled({ ...first, projectile }, 1.02, 0.95), three)
  const o2 = observe(scaled({ ...second, projectile }, 0.99, 0.95), three)
  const both = (shot2 = second): TruingSession[] => [
    { shot: first, observations: o1, fitMuzzleVelocity: true },
    { shot: shot2, observations: o2, fitMuzzleVelocity: true },
  ]

  it('recovers the shared drag factor and each muzzle velocity', () => {
    const r = trueDragSessions(projectile, both())
    expect(r.parameters.map((p) => [p.name, p.session])).toEqual([
      ['muzzleVelocity', 0],
      ['muzzleVelocity', 1],
      ['dragFactor', undefined],
    ])
    const truth = [790 * 1.02, 805 * 0.99, 0.95]
    r.parameters.forEach((p, i) => {
      expect(Math.abs(p.value / truth[i] - 1)).toBeLessThan(1e-6)
    })
    expect(r.degreesOfFreedom).toBe(3)
    // measured; guards the per-session skip in the Jacobian
    expect([r.trajectoryCount, r.steps]).toEqual([40, 2487])
    expect(r.residuals.map((x) => x.session)).toEqual([0, 0, 0, 1, 1, 1])
    for (const x of r.residuals) expect(Math.abs(x.residual)).toBeLessThan(1e-6)
    expect(r.shots.map((x) => x.muzzleVelocity)).toEqual([
      r.parameters[0].value,
      r.parameters[1].value,
    ])
    expect(r.shots[1].air).toBe(second.air)
    expect(r.shots[0].projectile.drag).toEqual({
      ...g7,
      bands: [
        {
          ballisticCoefficient: g7.bands[0].ballisticCoefficient / r.parameters[2].value,
          minVelocity: 0,
        },
      ],
    })
  })

  it('holds one session and fits the muzzle velocity of the other', () => {
    const r = trueDragSessions(projectile, [
      { shot: first, observations: observe(scaled({ ...first, projectile }, 1, 0.95), three) },
      { shot: second, observations: o2, fitMuzzleVelocity: true },
    ])
    expect(r.parameters.map((p) => [p.name, p.session, p.initial])).toEqual([
      ['muzzleVelocity', 1, 805],
      ['dragFactor', undefined, 1],
    ])
    const truth = [805 * 0.99, 0.95]
    r.parameters.forEach((p, i) => {
      expect(Math.abs(p.value / truth[i] - 1)).toBeLessThan(1e-6)
    })
    expect(r.shots.map((x) => x.muzzleVelocity)).toEqual([790, r.parameters[0].value])
  })

  it('takes firearm, zero and site from each session', () => {
    const own: TruingSession['shot'] = {
      ...second,
      firearm: { sightHeight: 0.08 },
      zero: { range: 200 },
      site: { latitude: 1.2, azimuth: 1 },
    }
    const coriolis = { coriolis: true }
    const r = trueDragSessions(
      projectile,
      [
        {
          shot: first,
          observations: observe(scaled({ ...first, projectile }, 1.02, 0.95), three, coriolis),
          fitMuzzleVelocity: true,
        },
        {
          shot: own,
          observations: observe(scaled({ ...own, projectile }, 0.99, 0.95), three, coriolis),
          fitMuzzleVelocity: true,
        },
      ],
      {},
      coriolis,
    )
    expect(r.parameters.map((p) => p.initial)).toEqual([790, 805, 1])
    const truth = [790 * 1.02, 805 * 0.99, 0.95]
    r.parameters.forEach((p, i) => {
      expect(Math.abs(p.value / truth[i] - 1)).toBeLessThan(1e-6)
    })
    expect(r.shots[1].site).toBe(own.site)
  })

  it('fits knots over two sessions', () => {
    const v = (shot: TruingSession['shot'], xs: number[]) =>
      observe(
        scaled({ ...shot, projectile }, 1, 0.95),
        xs.map((x): [Observation['kind'], number, number] => ['velocity', x, 1]),
      )
    const r = trueDragSessions(
      projectile,
      [
        { shot: first, observations: v(first, [0, 200, 400, 600, 800, 1000]) },
        { shot: second, observations: v(second, [0, 300, 600, 900]) },
      ],
      { knots: [1.5, 2] },
    )
    expect(r.parameters.map((p) => p.mach)).toEqual([1.5, 2])
    for (const p of r.parameters) expect(Math.abs(p.value / 0.95 - 1)).toBeLessThan(1e-6)
  })

  it('flies each session in its own air', () => {
    const r = trueDragSessions(projectile, both({ ...second, air: first.air }))
    expect(Math.abs(r.parameters[2].value / 0.95 - 1)).toBeGreaterThan(1e-2)
  })

  it('equals trueDrag for one session', () => {
    const obs = observe(scaled(base, 1.02, 0.95), mixed)
    const a = trueDrag(base, obs, { fitMuzzleVelocity: true })
    const { projectile: _, ...shot } = base
    const b = trueDragSessions(projectile, [{ shot, observations: obs, fitMuzzleVelocity: true }])
    expect(b.parameters.map(({ session, ...p }) => p)).toEqual(a.parameters)
    expect(b.residuals.map(({ session, ...x }) => x)).toEqual(a.residuals)
    const counts = (r: typeof a | typeof b) => [
      r.chiSquare,
      r.degreesOfFreedom,
      r.conditionNumber,
      r.iterations,
      r.trajectoryCount,
      r.steps,
    ]
    expect(counts(b)).toEqual(counts(a))
    expect(b.shots[0]).toEqual(a.shot)
    expect(a.parameters.some((p) => 'session' in p)).toBe(false)
    expect(a.residuals.some((x) => 'session' in x)).toBe(false)
  })

  it('weights each session by its own sigmas', () => {
    const sigmas = [2, 1, 3, 3, 0.5, 2, 4]
    const noise = [0.4, 0.7, -1.1, 0.2, 0.3, 1.4, -0.9]
    const obs = observe(
      scaled(base, 1, 0.95),
      [100, 200, 300, 400, 600, 800, 1000].map((x, i): [Observation['kind'], number, number] => [
        'velocity',
        x,
        sigmas[i],
      ]),
    ).map((x, i) => ({ ...x, value: x.value + noise[i] }))
    const a = trueDrag(base, obs)
    const { projectile: _, ...shot } = base
    const b = trueDragSessions(projectile, [
      { shot, observations: obs.slice(0, 3) },
      { shot, observations: obs.slice(3, 4) },
      { shot, observations: obs.slice(4) },
    ])
    expect(Math.abs(b.parameters[0].value / a.parameters[0].value - 1)).toBeLessThan(1e-10)
    expect(
      Math.abs(
        (b.parameters[0].standardUncertainty ?? 0) / (a.parameters[0].standardUncertainty ?? 1) - 1,
      ),
    ).toBeLessThan(1e-8)
  })

  describe('closed form in one dimension', () => {
    // gravity 0, flat Cd, level bore: v = v0 exp(-k c x) in each session's air
    const cd = 0.3
    const sigma = 2
    const k = 1.1
    const opts = { gravity: 0, coriolis: false, relativeTolerance: 1e-12, absoluteTolerance: 1e-10 }
    const airs = [standardAtmosphere(0), { ...standardAtmosphere(2000), temperature: 263.15 }]
    const v0s = [800, 760]
    const xs = [
      [100, 300, 500],
      [150, 400, 650, 900],
    ]
    const sessions = airs.map((air, s) => {
      const c = (airDensity(air) * cd * Math.PI * 0.00782 ** 2) / (8 * 0.01134)
      const values = xs[s].map((x) => v0s[s] * Math.exp(-k * c * x))
      const session: TruingSession = {
        shot: {
          muzzleVelocity: v0s[s] * 1.01,
          firearm: { sightHeight: 0 },
          air,
          zero: { elevationAngle: 0, windageAngle: 0 },
        },
        observations: values.map((value, i) => ({
          kind: 'velocity',
          range: xs[s][i],
          value,
          standardUncertainty: sigma,
        })),
        fitMuzzleVelocity: true,
      }
      // rows of d v / d ln v0 and of minus d v / d ln k, over sigma
      const a = values.map((v) => v / sigma)
      const b = values.map((v, i) => (k * c * xs[s][i] * v) / sigma)
      const dot = (p: number[], q: number[]) => p.reduce((t, x, i) => t + x * q[i], 0)
      return { session, info: dot(b, b) - dot(a, b) ** 2 / dot(a, a) }
    })
    const own = { ...projectile, drag: flat(cd) }
    const joint = trueDragSessions(
      own,
      sessions.map((x) => x.session),
      {},
      opts,
    )

    it('gives the closed-form sigma of the shared factor', () => {
      const f = joint.parameters[2]
      expect(Math.abs(f.value / k - 1)).toBeLessThan(1e-9)
      const expected = k / Math.sqrt(sessions.reduce((t, x) => t + x.info, 0))
      expect(Math.abs((f.standardUncertainty ?? 0) / expected - 1)).toBeLessThan(1e-6)
    })

    it('adds the information of the sessions', () => {
      const alone = sessions.map(
        (x) =>
          trueDragSessions(own, [x.session], {}, opts).parameters[1].standardUncertainty ??
          Number.NaN,
      )
      const sum = alone.reduce((t, x) => t + x ** -2, 0)
      expect(Math.abs((joint.parameters[2].standardUncertainty ?? 0) ** -2 / sum - 1)).toBeLessThan(
        1e-9,
      )
    })
  })

  it('rejects malformed sessions before any trajectory', () => {
    const plain = (f: () => unknown) => {
      try {
        f()
      } catch (e) {
        return e instanceof InputError && !(e instanceof TruingError)
      }
      return false
    }
    expect(plain(() => trueDragSessions(projectile, []))).toBe(true)
    expect(
      plain(() =>
        trueDragSessions(projectile, [
          { shot: first, observations: o1 },
          { shot: second, observations: [] },
        ]),
      ),
    ).toBe(true)
    const bare = o2.map(({ standardUncertainty, ...x }) => x)
    expect(
      plain(() =>
        trueDragSessions(projectile, [
          { shot: first, observations: o1 },
          { shot: second, observations: bare },
        ]),
      ),
    ).toBe(true)
    let reason: unknown
    try {
      trueDragSessions(projectile, [
        { shot: first, observations: o1.slice(0, 1), fitMuzzleVelocity: true },
        { shot: second, observations: o2.slice(0, 1), fitMuzzleVelocity: true },
      ])
    } catch (e) {
      reason = e instanceof TruingError && e.reason
    }
    expect(reason).toBe('underdetermined')
  })

  it('names the sessions in the estimate of a failed fit', () => {
    let error: TruingError | undefined
    try {
      trueDragSessions(projectile, both(), {}, { maxIterations: 1 })
    } catch (e) {
      if (e instanceof TruingError) error = e
    }
    expect(error?.reason).toBe('not-converged')
    expect(error?.estimate?.map((p) => [p.name, p.session])).toEqual([
      ['muzzleVelocity', 0],
      ['muzzleVelocity', 1],
      ['dragFactor', undefined],
    ])
  })
})
