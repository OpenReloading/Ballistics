import { describe, expect, it } from 'vitest'
import { nth } from '../src/errors.ts'
import {
  fitPowder,
  InputError,
  type InteriorLoad,
  interior,
  type LadderPoint,
  type PowderFit,
  powderConfidence,
  powderInputDefaults,
  powderPressureRange,
  similarPowdersPrior,
} from '../src/index.ts'

/** Synthetic rifle load (apps/docs/docs/models/interior-powder-fit.md): truth B_a 0.45 1/s, p_st 30 MPa. */
const load = (vivacity = 0.45): InteriorLoad => ({
  chamber: { volume: 3.4e-6, boreArea: 3.75e-5, boreDiameter: 6.9e-3 },
  barrel: { length: 0.6, twist: 0.254 },
  bullet: { mass: 0.0095 },
  charge: 0.0028,
  propellant: {
    specificEnergy: 3.9e6,
    gamma: 1.23,
    density: 1600,
    covolume: 1e-3,
    burn: {
      kind: 'vivacity',
      vivacity,
      exponent: 1,
      referencePressure: 98066.5,
      form: { kind: 'twoStage', a: 0.8, m: 0.5, q: 0.5, z1: 0.8 },
    },
    temperatureSensitivity: { reference: 294.15, cold: 0.004, hot: 0.004 },
  },
  propellantTemperature: 294.15,
  ignitionPressure: 5e6,
  startPressure: 30e6,
  resistance: { friction: 2e6 },
})
const charges = [2.6e-3, 2.7e-3, 2.8e-3, 2.9e-3, 3e-3]
/** Fixed noise pattern in units of sigma. */
const noise = [1, -1, 0.5, -1.5, 0.8]

/** Ladder generated by `interior`: velocity sigma 3 m/s, a pressure row with sigma 5 MPa on the charges in `withPressure`. */
const ladder = (withPressure: readonly number[] = [], n = 0, at = charges): LadderPoint[] =>
  at.map((charge, i) => {
    const r = interior({ ...load(), charge })
    if (!r.valid) throw new Error(r.reason)
    return {
      charge,
      muzzleVelocity: r.muzzleVelocity + n * nth(noise, i % 5) * 3,
      velocitySigma: 3,
      ...(withPressure.includes(charge)
        ? {
            peakPressure: r.peakBreechPressure,
            pressureSigma: 5e6,
            pressureBasis: 'transducer' as const,
          }
        : {}),
    }
  })

const fitLadder = (points: LadderPoint[], start = load(0.4)): PowderFit => fitPowder(start, points)
const velocityOnly = ladder()
const withPressure = ladder([2.8e-3])

describe('powder pressure range', () => {
  const velocityRange = powderPressureRange(fitLadder(velocityOnly), velocityOnly)
  const pressureRange = powderPressureRange(fitLadder(withPressure), withPressure)

  it('is wider for a velocity-only fit than with one pressure row on the same ladder', () => {
    expect(velocityRange.relativeHalfWidth).toBeGreaterThan(pressureRange.relativeHalfWidth)
    expect(velocityRange.relativeHalfWidth).toBeGreaterThan(0.02)
  })

  it('lists one band per ladder charge around the fitted peak pressure', () => {
    expect(velocityRange.points.map((p) => p.charge)).toEqual(charges)
    for (const p of velocityRange.points) {
      const r = interior({ ...load(), charge: p.charge })
      if (!r.valid) throw new Error(r.reason)
      expect(p.peakPressure).toBeCloseTo(r.peakBreechPressure, -3)
      expect(p.lower).toBeLessThan(p.peakPressure)
      expect(p.upper).toBeGreaterThan(p.peakPressure)
      expect(p.upper - p.peakPressure).toBeCloseTo(p.peakPressure - p.lower, 3)
      // the independent combination stays between the fit alone and the fully correlated limit
      expect(p.standardUncertainty).toBeGreaterThan(p.fitUncertainty)
      expect(p.standardUncertainty).toBeLessThanOrEqual(p.correlatedLimit)
    }
  })

  it('adds each fixed input in quadrature, skips fitted and absent ones', () => {
    const used = velocityRange.contributions.map((c) => c.input)
    expect(used).toEqual([
      'caseCapacity',
      'propellantEnergy',
      'startPressure',
      'boreFriction',
      'propellantTemperature',
    ])
    const p = nth(velocityRange.points, 2)
    const effects = velocityRange.contributions.map((c) => nth(c.effects, 2))
    expect(p.standardUncertainty).toBeCloseTo(Math.hypot(p.fitUncertainty, ...effects), 3)
    // a larger chamber and a lower energy lower the refitted peak pressure at the same velocities
    expect(Math.abs(nth(nth(velocityRange.contributions, 0).effects, 2))).toBeGreaterThan(0)
    expect(velocityRange.coverageFactor).toBeCloseTo(1.645, 3)
    expect(velocityRange.level).toBe(0.9)
    expect(velocityRange.extrapolated).toBe(false)
  })

  it('skips a fitted parameter and an input the load does not carry', () => {
    const bare = { ...load(0.4), resistance: undefined }
    const { temperatureSensitivity: _, ...propellant } = bare.propellant
    const noTemperature = { ...bare, propellant }
    const rows = ladder(charges)
    const both = fitPowder(noTemperature, rows, {
      parameters: ['burnRate', 'startPressure'],
    })
    const range = powderPressureRange(both, rows, {
      fit: { parameters: ['burnRate', 'startPressure'] },
    })
    const skipped = Object.fromEntries(range.contributions.map((c) => [c.input, c.skipped]))
    expect(skipped).toEqual({
      caseCapacity: undefined,
      propellantEnergy: undefined,
      startPressure: 'fitted',
      boreFriction: 'absent',
      propellantTemperature: 'absent',
    })
  })

  it('takes the measured defaults, caller values and extra inputs', () => {
    expect(powderInputDefaults.caseCapacity).toEqual({
      unit: 'relative',
      measured: 0.005,
      estimated: 0.03,
    })
    const narrow = powderPressureRange(fitLadder(velocityOnly), velocityOnly, {
      inputs: { caseCapacity: { basis: 'measured' } },
    })
    expect(narrow.relativeHalfWidth).toBeLessThan(velocityRange.relativeHalfWidth)
    expect(nth(narrow.contributions, 0)).toMatchObject({
      basis: 'measured',
      standardUncertainty: 0.005,
    })
    const extra = powderPressureRange(fitLadder(velocityOnly), velocityOnly, {
      inputs: {
        bulletMass: { standardUncertainty: 0.02 },
        boreFriction: { standardUncertainty: 0 },
      },
    })
    expect(extra.contributions.map((c) => c.input)).toContain('bulletMass')
    expect(extra.contributions.map((c) => c.input)).not.toContain('boreFriction')
    expect(extra.relativeHalfWidth).toBeGreaterThan(0)
  })

  it('shifts the temperature of the points that carry their own', () => {
    const own = velocityOnly.map((x) => ({ ...x, propellantTemperature: 294.15 }))
    const range = powderPressureRange(fitLadder(own), own, {
      inputs: { propellantTemperature: { standardUncertainty: 5 } },
    })
    const t = range.contributions.find((c) => c.input === 'propellantTemperature')
    expect(t?.unit).toBe('K')
    // one offset common to every point is absorbed by the refitted burn coefficient
    expect(t?.skipped).toBeUndefined()
    expect(Math.abs(nth(t?.effects ?? [], 2))).toBeLessThan(1e3)
  })

  it('marks points outside the ladder and evaluates at their conditions', () => {
    const range = powderPressureRange(fitLadder(velocityOnly), velocityOnly, {
      points: [{ charge: 3.2e-3, barrelLength: 0.5 }, { charge: 2.8e-3 }],
    })
    expect(range.extrapolated).toBe(true)
    expect(nth(range.points, 0).barrelLength).toBe(0.5)
    expect(nth(range.points, 0).peakPressure).toBeGreaterThan(nth(range.points, 1).peakPressure)
  })

  it('reports an input whose refit fails and refuses bad options', () => {
    const range = powderPressureRange(fitLadder(velocityOnly), velocityOnly, {
      // the shifted start pressure stays valid, a chamber twenty times larger has no valid run
      inputs: { caseCapacity: { standardUncertainty: 50 } },
    })
    expect(nth(range.contributions, 0).skipped).toBe('refit-failed')
    expect(() =>
      powderPressureRange(fitLadder(velocityOnly), velocityOnly, {
        inputs: { gamma: { standardUncertainty: -1 } },
      }),
    ).toThrow(InputError)
    expect(() =>
      powderPressureRange(fitLadder(velocityOnly), velocityOnly, { points: [] }),
    ).toThrow(InputError)
  })
})

describe('prior from similar powders', () => {
  const target = { burnRate: 0.45, energy: 3.9e6 }
  const neighbours = [
    { burnRate: 0.4, energy: 3.8e6 },
    { burnRate: 0.5, energy: 4e6 },
    { burnRate: 0.6, energy: 3.9e6 },
    { burnRate: 0.45, energy: 3.7e6 },
    { burnRate: 0.42, energy: 4.1e6 },
    { burnRate: 3, energy: 3.9e6 },
    { burnRate: 0.01, energy: 3.9e6 },
  ]

  it('takes the mean and standard deviation of the log burn coefficient of the nearest five', () => {
    const r = similarPowdersPrior(target, neighbours)
    const logs = [0.4, 0.5, 0.6, 0.45, 0.42].map(Math.log)
    const mean = logs.reduce((s, x) => s + x, 0) / 5
    const sd = Math.sqrt(logs.reduce((s, x) => s + (x - mean) ** 2, 0) / 4)
    expect(r).toMatchObject({ count: 5, weak: false })
    expect(r.prior.value).toBeCloseTo(Math.exp(mean), 12)
    expect(r.prior.sigma).toBeCloseTo(sd, 12)
  })

  it('gives a weak prior on the target value below three neighbours and floors the spread', () => {
    expect(similarPowdersPrior(target, neighbours.slice(0, 2))).toEqual({
      prior: { value: 0.45, sigma: 1 },
      count: 2,
      weak: true,
    })
    const same = Array.from({ length: 3 }, () => ({ burnRate: 0.4, energy: 3.9e6 }))
    expect(similarPowdersPrior(target, same).prior.sigma).toBe(0.05)
    expect(similarPowdersPrior(target, neighbours, 3).count).toBe(3)
  })

  it('refuses a powder without a positive value or a bad count', () => {
    expect(() => similarPowdersPrior(target, [{ burnRate: 0, energy: 1 }])).toThrow(InputError)
    expect(() => similarPowdersPrior(target, neighbours, 0)).toThrow(InputError)
  })

  it('pulls a short ladder toward the prior and marks the fit refined', () => {
    const short = ladder([], 1, [2.8e-3, 2.9e-3])
    const plain = fitPowder(load(0.4), short)
    expect(plain.basis).toBe('from-scratch')
    const prior = { value: 0.6, sigma: 0.1 }
    const refined = fitPowder(load(0.4), short, { priors: { burnRate: prior } })
    expect(refined.basis).toBe('refined')
    const value = (f: PowderFit) => nth(f.parameters, 0).value
    expect(Math.abs(Math.log(value(refined) / 0.6))).toBeLessThan(
      Math.abs(Math.log(value(plain) / 0.6)),
    )
    // a prior on the start pressure alone does not make the fit refined
    const start = fitPowder(load(0.4), withPressure, {
      parameters: ['burnRate', 'startPressure'],
      priors: { startPressure: { value: 30e6, sigma: 0.5 } },
    })
    expect(start.basis).toBe('from-scratch')
  })
})

describe('confidence label', () => {
  const velocityFit = fitLadder(velocityOnly)
  const velocityRange = powderPressureRange(velocityFit, velocityOnly)
  const rules = (range: typeof velocityRange, width: number) => ({
    ...range,
    relativeHalfWidth: width,
  })

  it('sets the label from the relative half-width at 10 % and 25 %', () => {
    const at = (w: number) => powderConfidence(velocityFit, rules(velocityRange, w)).label
    expect([at(0.05), at(0.1), at(0.1001), at(0.25), at(0.2501), at(0.6)]).toEqual([
      'tight',
      'tight',
      'moderate',
      'moderate',
      'loose',
      'loose',
    ])
  })

  it('states the basis and the reasons of a velocity-only fit with an estimated capacity', () => {
    const c = powderConfidence(velocityFit, velocityRange)
    expect(c.reasons).toEqual(['no-pressure', 'capacity-estimated'])
    expect(c.basis).toBe('from-scratch')
    expect(c.relativeHalfWidth).toBe(velocityRange.relativeHalfWidth)
    expect(c.label).toBe('tight')
    // looser energy and capacity uncertainties widen the range into the next classes
    const label = (energy: number) =>
      powderConfidence(
        velocityFit,
        powderPressureRange(velocityFit, velocityOnly, {
          inputs: { propellantEnergy: { standardUncertainty: energy } },
        }),
      )
    expect(label(0.05).label).toBe('moderate')
    expect(label(0.1).label).toBe('loose')
  })

  it('drops no-pressure and tightens with a pressure row and a measured capacity', () => {
    const f = fitLadder(withPressure)
    const r = powderPressureRange(f, withPressure, {
      inputs: { caseCapacity: { basis: 'measured' } },
    })
    const c = powderConfidence(f, r)
    expect(c.reasons).toEqual([])
    expect(c.label).toBe('tight')
    expect(c.relativeHalfWidth).toBeLessThan(velocityRange.relativeHalfWidth)
  })

  it('flags a narrow ladder and an extrapolated point', () => {
    const narrow = ladder([], 0, [2.8e-3, 2.82e-3, 2.84e-3])
    const f = fitLadder(narrow)
    const r = powderPressureRange(f, narrow, { points: [{ charge: 3.2e-3 }] })
    expect(powderConfidence(f, r).reasons).toEqual([
      'no-pressure',
      'capacity-estimated',
      'narrow-ladder',
      'extrapolated',
    ])
  })

  it('flags a residual trend that runs in one sign block and not noise', () => {
    // a velocity trend the one parameter cannot follow: 6 m/s steps along the charges
    const bent = ladder().map((x, i) => ({ ...x, muzzleVelocity: x.muzzleVelocity + (i - 2) * 6 }))
    const f = fitLadder(bent)
    expect(f.dataChiSquare / f.residuals.length).toBeGreaterThan(1)
    const r = powderPressureRange(f, bent)
    expect(powderConfidence(f, r).reasons).toContain('residual-trend')
    const noisy = ladder([], 1)
    const g = fitLadder(noisy)
    expect(powderConfidence(g, powderPressureRange(g, noisy)).reasons).not.toContain(
      'residual-trend',
    )
    // an unweighted ladder is never tested for a trend
    const bare = bent.map(({ velocitySigma: _, ...x }) => x)
    const h = fitLadder(bare)
    expect(powderConfidence(h, powderPressureRange(h, bare)).reasons).not.toContain(
      'residual-trend',
    )
  })

  it('flags a start pressure that moves with the burn coefficient', () => {
    const f = fitPowder(load(0.4), ladder([2.6e-3, 3e-3]), {
      parameters: ['burnRate', 'startPressure'],
    })
    const r = powderPressureRange(f, ladder([2.6e-3, 3e-3]), {
      fit: { parameters: ['burnRate', 'startPressure'] },
    })
    const correlated = {
      ...f,
      correlation: [
        [1, -0.95],
        [-0.95, 1],
      ],
    }
    expect(powderConfidence(correlated, r).reasons).toContain('start-pressure-correlated')
    expect(
      powderConfidence(
        {
          ...f,
          correlation: [
            [1, 0.5],
            [0.5, 1],
          ],
        },
        r,
      ).reasons,
    ).not.toContain('start-pressure-correlated')
  })

  it('flags a weak prior and a fit outside the similar powders', () => {
    const near = similarPowdersPrior(
      { burnRate: 0.45, energy: 3.9e6 },
      [0.68, 0.72, 0.7].map((burnRate) => ({ burnRate, energy: 3.9e6 })),
    )
    const wide = powderConfidence(velocityFit, velocityRange, { similar: near })
    expect(wide.reasons).toContain('outside-similar-powders')
    const far = { ...near, prior: { value: 0.9, sigma: 1 } }
    expect(powderConfidence(velocityFit, velocityRange, { similar: far }).reasons).not.toContain(
      'outside-similar-powders',
    )
    const weak = powderConfidence(velocityFit, velocityRange, {
      similar: similarPowdersPrior({ burnRate: 0.45, energy: 3.9e6 }, []),
    })
    expect(weak.reasons).toContain('weak-prior')
    expect(weak.reasons).not.toContain('outside-similar-powders')
  })

  it('names an input whose refit failed and refuses a range without width', () => {
    const failed = {
      ...velocityRange,
      contributions: velocityRange.contributions.map((c) => ({
        ...c,
        skipped: 'refit-failed' as const,
      })),
    }
    expect(powderConfidence(velocityFit, failed).reasons).toContain('input-refit-failed')
    expect(() => powderConfidence(velocityFit, rules(velocityRange, Number.NaN))).toThrow(
      InputError,
    )
  })
})
